    private static void add(String id, String title, String content) {
        PromptPreset p = new PromptPreset();
        p.setId(id);
        p.setTitle(title);
        p.setContent(content);
        p.setEnabled(false);
        AGENTS.add(p);
    }

    /** 全部内置智能体列表（不可变视图） */
    public static List<PromptPreset> list() {
        return Collections.unmodifiableList(AGENTS);
    }

    /** 按 ID 取内置智能体提示词内容；非内置 ID 或未找到返回 null */
    public static String contentById(String id) {
        if (id == null || !id.startsWith("builtin-")) {
            return null;
        }
        for (PromptPreset p : AGENTS) {
            if (p.getId().equals(id)) {
                return p.getContent();
            }
        }
        return null;
    }
