function savedLocale() {
  try { return localStorage.getItem('locale') } catch (e) { return null }
}

const i18n = createI18n({
  legacy: false,
  locale: savedLocale() === 'en' ? 'en' : 'zh',
  fallbackLocale: 'zh',
  messages: { zh, en }
})

// 切换语言并持久化；同步 html lang 属性
export function setLocale(locale) {
  const l = locale === 'en' ? 'en' : 'zh'
  i18n.global.locale.value = l
  try { localStorage.setItem('locale', l) } catch (e) { /* ignore */ }
  document.documentElement.setAttribute('lang', l === 'en' ? 'en' : 'zh-CN')
}

export function getLocale() {
  return i18n.global.locale.value
}

export default i18n

